#!/usr/bin/env python3
"""gen_regs.py -- one register description, three readers.

Reads dma_regs.yaml and writes
  ../rtl/dma_regs_pkg.sv the package version 2 and the testbench import
  regs_table.md          the register table the chapter includes
then prints the map, and with --check fails if either file on disk
differs from what the YAML now says (CI runs it that way, so the RTL,
the testbench and the book cannot drift apart).
"""
import pathlib
import sys

import yaml

HERE = pathlib.Path(__file__).resolve().parent
PKG = HERE.parent / "rtl" / "dma_regs_pkg.sv"
TABLE = HERE / "regs_table.md"


def width(f):
    hi, lo = f["bits"]
    return hi - lo + 1


def bits(f):
    hi, lo = f["bits"]
    return f"{hi}" if hi == lo else f"{hi}:{lo}"


def package(spec):
    v2 = spec["v2"]
    out = ["// dma_regs_pkg.sv -- GENERATED by regs/gen_regs.py from",
           "// regs/dma_regs.yaml. Edit the YAML, not this file.",
           "package dma_regs_pkg;",
           f"  localparam int NCH        = {v2['channels']};",
           f"  localparam int CH_STRIDE  = 'h{v2['stride']:02X};"]
    for r in v2["registers"]:
        out.append(f"  localparam int {r['name']:<10} = 'h{r['offset']:02X};")
        for f in r["fields"]:
            if f["name"] in ("zero", "addr", "words"):
                continue
            mask = ((1 << width(f)) - 1) << f["bits"][1]
            nm = f"{r['name']}_{f['name'].upper()}"
            out.append(f"  localparam int {nm:<16} = 'h{mask:X};")
    out.append("  // The one AXI response that means success")
    out.append("  localparam int RESP_OKAY   = 0;")
    out.append("endpackage")
    return "\n".join(out) + "\n"


def table(spec):
    rows = ["| Version | Offset | Register | Bits | Field | Access | Meaning |",
            "| --- | --- | --- | --- | --- | --- | --- |"]
    for key in ("v1", "v2"):
        v = spec[key]
        for r in v["registers"]:
            off = f"0x{r['offset']:02X}"
            if v["channels"] > 1:
                off += f" + 0x{v['stride']:02X} x n"
            for f in sorted(r["fields"], key=lambda f: -f["bits"][0]):
                rows.append(f"| {key} | {off} | `{r['name']}` | {bits(f)} | "
                            f"`{f['name']}` | {f['access']} | {f['note']} |")
    return "\n".join(rows) + "\n"


def main():
    spec = yaml.safe_load((HERE / "dma_regs.yaml").read_text())
    want = {PKG: package(spec), TABLE: table(spec)}
    if "--check" in sys.argv:
        stale = [p.name for p, t in want.items()
                 if not p.exists() or p.read_text() != t]
        if stale:
            print("stale generated files:", ", ".join(stale))
            return 1
        print("generated files match dma_regs.yaml")
    else:
        for p, t in want.items():
            p.write_text(t)
    for key in ("v1", "v2"):
        v = spec[key]
        print(f"{v['title']}: {v['channels']} channel(s), "
              f"{len(v['registers'])} registers each")
        for r in v["registers"]:
            fl = ", ".join(f"{f['name']}[{bits(f)}] {f['access']}"
                           for f in r["fields"])
            print(f"  0x{r['offset']:02X} {r['name']:<9} {fl}")
    for rule in spec["v2"]["rules"]:
        print("  rule:", rule)
    return 0


if __name__ == "__main__":
    sys.exit(main())

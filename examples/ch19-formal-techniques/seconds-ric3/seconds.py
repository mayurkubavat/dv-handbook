"""seconds.py -- the one table of wall-clock seconds in the chapter.

    python3 seconds.py

Runs seconds.tcl through the book's wrapper and reads the tool's own
report, the one place where the time of each `prove` is printed. Only
rows that end with a verdict are run (no limit is timed). What this
script prints holds the verdicts only, so that two runs print the
same text; with MEASURE=1 in the environment the seconds go to
tbl-seconds.md, with the date and the versions of the tools, and that
file then differs from run to run by design. The table is written
with the previous chapter's helpers (its common/tables.py, by path).
"""
import datetime
import os
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.dont_write_bytecode = True      # leave the other chapter's tree as it is
sys.path.insert(0, str(HERE.parent.parent / "ch18-formal-property-verification"
                       / "common"))
import tables  # noqa: E402

LIMIT = 60
LABEL = {
    "mem-box": "RAM of 256 words, storage boxed, contract assumed",
    "mem-helper": "RAM of 256 words, the helper at the slot",
    "mem-store": "RAM of 256 words, the contract, helper assumed",
    "mem-flat4": "RAM of 16 words, whole design",
    "mem-flat8": "RAM of 256 words, whole design",
    "pipe-hp": "pipe of two FIFOs of 16, boxed, the parent helper",
    "pipe-under-hp": "pipe of two FIFOs of 16, boxed, helper assumed",
    "pipe-box": "pipe of two FIFOs of 16, boxed, no helper",
    "pipe-flat": "pipe of two FIFOs of 16, flat, no helper",
    "mul-whole": "8-bit multiplier miter, whole",
    "mul-case0": "8-bit multiplier miter, case `a[7:6] == 0`",
    "mul-case1": "8-bit multiplier miter, case `a[7:6] == 1`",
    "mul-case2": "8-bit multiplier miter, case `a[7:6] == 2`",
    "mul-case3": "8-bit multiplier miter, case `a[7:6] == 3`",
    "kth-history": "k-th word of a FIFO of 4, history variable",
    "kth-prophecy": "k-th word of a FIFO of 4, prophecy at the pop",
}
RUNS = 19

tables.need("informal", "ric3")
rc, _ = tables.shell("seconds.tcl", "build/informal")
raw = (HERE / "build" / "informal" / "report.txt").read_text()
runs, key = [], None
for line in raw.splitlines():
    if line.startswith("run|"):
        key = tuple(line.split("|")[1:])
        continue
    if key and line.split()[:1] == [key[2]]:
        status = line.split()[2]
        t = re.search(r"([0-9]+\.[0-9]+) s$", line)
        runs.append((key, status, t.group(1) if t else None))
        key = None
if rc or len(runs) != RUNS:
    print(f"FAILED: seconds.tcl exit status {rc}, {len(runs)} runs")
    sys.exit(1)

rows, failed = [], 0
print(f"limit: {LIMIT} s for each run; the seconds are in "
      f"tbl-seconds.md and not here")
for (name, engine, prop), status, seconds in runs:
    label = LABEL[name]
    plain = label.replace("`", "")
    print(f"  {plain:52s} {prop:13s} {engine:14s} {status}")
    if status != "proven":
        print("FAILED: expected proven")
        failed += 1
    rows.append([tables.cell(label), f"`{prop}`", f"`{engine}`",
                 seconds or "?"])
if failed:
    sys.exit(1)

# The table is rewritten only when asked for (MEASURE=1), so that an
# ordinary run checks the verdicts and leaves the committed table, and
# the date in its caption, as they were measured.
if os.environ.get("MEASURE") != "1":
    print("verdict: every run proven, as the chapter states")
    sys.exit(0)
today = datetime.date.today().isoformat()
tables.write(
    HERE / "tbl-seconds.md",
    ["Design and check", "Property", "Engine", "Seconds"],
    rows,
    f"Wall-clock seconds of single proofs on {today}, on the machine "
    f"that built this copy of the book, with InFormal "
    f"{tables.version('informal')} (commit `{tables.PIN}`) and rIC3 "
    f"{tables.version('ric3')}; generated by the example "
    f"`seconds-ric3`, one property and one engine a run, {LIMIT} "
    "seconds allowed, and only runs that ended with a proof. One run "
    "is not a benchmark: read the column for its orders of magnitude. "
    "{#tbl-ch19-seconds}",
    align=["---", "---", "---", "--:"])
print("verdict: every run proven, as the chapter states")

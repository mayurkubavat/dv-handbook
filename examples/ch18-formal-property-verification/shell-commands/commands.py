"""commands.py -- the table of shell commands, from one session.

    python3 commands.py

commands.list holds one command to a line with a few words on what
it is for. This script wraps each line so that an error does not end
the session, runs all of them in order through the tool's shell, and
reads back for each one: whether it raised an error, what it
returned, what the tool printed, and how many properties existed
afterwards. The last column of the table is built from those four
facts by the rules in `effect` and from nothing else. The run fails
when the number of commands the tool refuses or ignores is not the
number the chapter states.
"""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "common"))
import tables  # noqa: E402

COUNTS = {"runs": 36, "error": 4, "ignored": 2}
WRAP = r'''
set here [file dirname [info script]]/..
proc step {n cmd} {
  puts "begin\t$n"
  set rc [catch {uplevel #0 $cmd} msg]
  set props -
  catch {set props [llength [get_property_list]]}
  puts "end\t$n\t$rc\t$props\t[string map [list "\n" " / "] $msg]"
}
'''


def effect(rc, value, printed, before, after):
    """(class, the words of the last column) for one command."""
    if rc:
        return "error", f"error: {value}".replace("`", "'")
    said = [p[len("informal: "):] for p in printed
            if p.startswith("informal: ")]
    table = any(p.startswith("property ") for p in printed)
    words = []
    if before != after and "-" not in (before, after):
        n = int(after) - int(before)
        words.append(f"{abs(n)} propert{'y' if abs(n) == 1 else 'ies'} "
                     f"{'more' if n > 0 else 'fewer'}")
    if table:
        words.append("prints the property table")
    if value.startswith("proven "):
        words.append(f"returns the counts `{value}`")
    elif " / " in value:
        words.append("returns several lines of text")
    elif value:
        words.append(f"returns `{value}`")
    if said:
        return "ignored", "; ".join([f"says: {said[0]}"] + words)
    return "runs", "; ".join(words) or "accepted; returns nothing"


tables.need("informal")
entries = []
for line in (HERE / "commands.list").read_text().splitlines():
    if line.startswith("== "):
        entries.append(("group", line[3:], ""))
    elif line and not line.startswith("#"):
        command, purpose = line.split(" ## ")
        entries.append(("row", command, purpose))
work = HERE / "build"
work.mkdir(exist_ok=True)
steps = [WRAP]
for i, (kind, command, _) in enumerate(entries):
    if kind == "row":
        steps.append(f"step {i} {{{command}}}")
(work / "steps.tcl").write_text("\n".join(steps) + "\n")
rc, report = tables.shell("build/steps.tcl", "build/informal")
if rc:
    print(report[-2000:])
    print(f"FAILED: the session ended with exit status {rc}")
    sys.exit(1)

got, printed = {}, []
for line in report.splitlines():
    part = line.split("\t")
    if part[0] == "begin":
        printed = []
    elif part[0] == "end":
        got[int(part[1])] = (int(part[2]), part[4] if len(part) > 4
                             else "", printed, part[3])
    else:
        printed.append(line)

rows, tally, before = [], dict.fromkeys(COUNTS, 0), "0"
print(f"tool: informal {tables.version('informal')}; one session, "
      f"{len(got)} commands")
for i, (kind, command, purpose) in enumerate(entries):
    if kind == "group":
        print(f"== {command}")
        rows.append([f"**{command}**", "", ""])
        continue
    if i not in got:
        print(f"FAILED: no result for: {command}")
        sys.exit(1)
    code, value, said, after = got[i]
    klass, words = effect(code, value, said, before, after)
    before = after
    tally[klass] += 1
    shown = command.replace("$here/../", "").replace("$here/", "")
    print(f"  {shown}")
    plain = re.sub("`", "", words)
    print(f"      {plain}" if klass == "error"
          else f"      {klass}: {plain}")
    rows.append([tables.cell(f"`{shown}`"), tables.cell(purpose),
                 tables.cell(words)])
print("commands: " + ", ".join(f"{n} {k}" for k, n in tally.items()))
if tally != COUNTS:
    print(f"FAILED: the counts were {COUNTS} when the chapter was "
          f"written")
    sys.exit(1)

tables.write(
    HERE / "tbl-shell.md",
    ["Command", "What it is for", "What the tool did"],
    rows,
    f"Shell commands and InFormal {tables.version('informal')} (commit "
    f"`{tables.PIN}`), generated by the example `shell-commands`: "
    "the lines run top to bottom in one session, each caught so that "
    "an error does not end it, and the last column is what was "
    "measured for that line: an error message, a message the tool "
    "printed, a change in the number of properties, the value "
    "returned. Paths are shown relative to the chapter's examples. "
    "{#tbl-ch18-shell}", grid=True, widths=[30, 24, 40])
print("wrote tbl-shell.md")

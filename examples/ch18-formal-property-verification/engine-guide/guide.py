"""guide.py -- the engine table, from one run of guide.tcl.

    python3 guide.py

Runs guide.tcl through the book's wrapper, reads its "cell|" lines,
prints the table as text and writes it as tbl-engines.md, which the
chapter includes. A cell is a verdict, with the depth where an
in-house engine reported one, or "no verdict in 4 s". The depth of a
counterexample from the external engine is left out: it need not be
the shortest. The last column applies the chapter's rule to the kind
of answer expected and checks that the engine it names did answer.
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "common"))
import tables  # noqa: E402

ENGINES = ["informal-bmc", "informal-kind", "informal-ic3", "ric3-ic3"]
LIMIT = "4 s"
# key: (situation, design and property, kind of answer expected)
ROWS = {
    "bug16": ("a bug 16 steps from reset",
              "counter, `cnt != 16`", "trace"),
    "bug64": ("a bug 64 steps from reset",
              "counter, `cnt != 64`", "trace"),
    "onestep": ("a fact one step shows",
                "FIFO of 8, `CountPtrs_A`", "step"),
    "reach": ("a fact about which states are reachable",
              "FIFO of 8, `EmptyPtrs_A`", "reach"),
    "cover": ("a cover that is reachable",
              "repaired FIFO of 16, `FullReached_C`", "trace"),
    "nocover": ("a cover that is not",
                "first chapter's FIFO, `FullReached_C`", "reach"),
    "live": ("liveness under a fairness assumption",
             "requester, `s_eventually gnt`", "live"),
    "dma": ("a rule of a larger design",
            "DMA, `ArStable_A`", "reach"),
}
RULE = {"trace": "informal-bmc", "step": "informal-kind",
        "reach": "informal-ic3", "live": "informal-ic3"}

tables.need("informal", "ric3")
rc, report = tables.shell("guide.tcl", "build/informal")
cells = {}
for line in report.splitlines():
    if line.startswith("cell|"):
        _, key, engine, status, depth = line.split("|")
        cells[key, engine] = (status, int(depth))
    elif line.startswith("unexpected:"):
        print(line)
if rc or len(cells) != len(ROWS) * len(ENGINES):
    print(f"FAILED: guide.tcl exit status {rc}, {len(cells)} cells")
    sys.exit(1)


def text(key, engine):
    status, depth = cells[key, engine]
    if status == "undetermined":
        return f"no verdict in {LIMIT}"
    if depth >= 0 and engine != "ric3-ic3":
        return f"{status}, depth {depth}"
    return status


rows = []
print(f"tool: informal {tables.version('informal')}, "
      f"rIC3 {tables.version('ric3')}; limit {LIMIT} for each cell")
for key, (what, where, kind) in ROWS.items():
    first = RULE[kind]
    if cells[key, first][0] == "undetermined":
        print(f"FAILED: {first} gave no verdict on its own row, {key}")
        sys.exit(1)
    answers = [text(key, e) for e in ENGINES]
    print(f"{what} ({where.replace('`', '')})")
    for engine, answer in zip(ENGINES, answers):
        print(f"    {engine:14s} {answer}")
    print(f"    first choice   {first}")
    rows.append([tables.cell(what), tables.cell(where)]
                + [tables.cell(a) for a in answers] + [f"`{first}`"])

tables.write(
    HERE / "tbl-engines.md",
    ["Situation", "Design and property"] + [f"`{e}`" for e in ENGINES]
    + ["First choice"], rows,
    f"Which engine answered what, one engine to a run and {LIMIT} to "
    f"a property, on InFormal {tables.version('informal')} (commit "
    f"`{tables.PIN}`) with rIC3 {tables.version('ric3')} as its "
    "external engine. Generated by the example `engine-guide`. A depth "
    "counts the reset cycle as 0. *No verdict* is a statement about "
    "the limit, not about the engine. The last column is the engine "
    "the rule of this section names for the kind of answer expected; "
    "the script fails if that engine did not answer. "
    "{#tbl-ch18-engines}")
print("wrote tbl-engines.md")

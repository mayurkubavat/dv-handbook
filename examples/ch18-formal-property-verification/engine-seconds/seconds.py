"""seconds.py -- the one table of wall-clock seconds in the chapter.

    python3 seconds.py

Runs seconds.tcl through the book's wrapper and reads the tool's own
report, the one place where the time of each `prove` is printed. What
this script prints holds the verdicts only, so that two runs print
the same text; the seconds go to tbl-seconds.md, with the date and
the versions of the tools, and that file differs from run to run by
design. The verdicts are checked against the ones the chapter
states; the seconds are not checked against anything.
"""
import datetime
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "common"))
import tables  # noqa: E402

LIMIT = 10
LABEL = {"bug": "counter, a bug {} steps from reset",
         "fifo": "FIFO of {}, `EmptyPtrs_A`",
         "help": "FIFO of {}, `EmptyPtrs_A`, helper assumed"}
WANT = {
    ("bug16", "informal-bmc"): "cex", ("bug64", "informal-bmc"): "cex",
    ("bug256", "informal-bmc"): "cex",
    ("bug1024", "informal-bmc"): "undetermined",
    ("bug1024", "ric3-ic3"): "cex",
    ("fifo2", "informal-kind"): "proven",
    ("fifo4", "informal-kind"): "undetermined",
    ("fifo64", "informal-ic3"): "undetermined",
    ("fifo64", "ric3-ic3"): "proven",
}

tables.need("informal", "ric3")
rc, _ = tables.shell("seconds.tcl", "build/informal")
raw = (HERE / "build" / "informal" / "report.txt").read_text()
runs, key = [], None
for line in raw.splitlines():
    if line.startswith("run|"):
        key = tuple(line.split("|")[1:])
        continue
    m = re.match(r"\S+\s+assert\s+(\w+)", line)
    if key and m:
        t = re.search(r"([0-9]+\.[0-9]+) s$", line)
        runs.append((key, m.group(1), t.group(1) if t else None))
        key = None
if rc or len(runs) != 20:
    print(f"FAILED: seconds.tcl exit status {rc}, {len(runs)} runs")
    sys.exit(1)

rows, failed = [], 0
print(f"limit: {LIMIT} s for each run; the seconds are in "
      f"tbl-seconds.md and not here")
for (name, engine), status, seconds in runs:
    kind, size = re.match(r"([a-z]+)(\d+)", name).groups()
    want = WANT.get((name, engine), "proven")
    label = LABEL[kind].format(size)
    plain = label.replace("`", "")
    shown = "no verdict" if status == "undetermined" else status
    print(f"  {plain:44s} {engine:14s} {shown}")
    if status != want:
        print(f"FAILED: expected {want}")
        failed += 1
    cell = (f"none in {LIMIT} s" if status == "undetermined"
            else seconds or "?")
    rows.append([label, f"`{engine}`", shown, cell])
if failed:
    sys.exit(1)

today = datetime.date.today().isoformat()
ric3 = tables.version("ric3")
tables.write(
    HERE / "tbl-seconds.md",
    ["Design and property", "Engine", "Verdict", "Seconds"],
    rows,
    f"Wall-clock seconds of single runs on {today}, on the machine "
    f"that built this copy of the book, with InFormal "
    f"{tables.version('informal')} (commit `{tables.PIN}`) and rIC3 "
    f"{ric3}; generated by the example `engine-seconds`, one "
    f"property and one engine a run, {LIMIT} seconds allowed. One "
    "run is not a benchmark: read the column for its orders of "
    "magnitude and for where it stops. {#tbl-ch18-seconds}",
    align=["---", "---", "---", "--:"])
print("verdict: every run ended as the chapter states")
